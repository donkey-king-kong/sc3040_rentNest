#!/usr/bin/env python3
"""Validate migration invariants in a new disposable LOCAL PostgreSQL database."""
import os
import subprocess
import uuid
from pathlib import Path


def main() -> None:
    # Do not inherit a remote PGHOST/PGSERVICE from a developer's shell.
    env = {key: value for key, value in os.environ.items() if not key.startswith("PG")}
    env["PGHOST"] = "/tmp"
    database = "rentnest_enquiry_test_" + uuid.uuid4().hex[:10]
    subprocess.run(["createdb", database], env=env, check=True)

    def sql(statement: str, success: bool = True) -> str:
        result = subprocess.run(
            ["psql", "-X", "-v", "ON_ERROR_STOP=1", "-At", "-d", database],
            input=statement, text=True, capture_output=True, env=env)
        if (result.returncode == 0) != success:
            raise AssertionError(result.stderr or result.stdout)
        return result.stdout.strip()

    def migrate(success: bool = True) -> None:
        result = subprocess.run(
            ["psql", "-X", "-v", "ON_ERROR_STOP=1", "-d", database, "-f",
             str(Path(__file__).with_name("migrate-listing-enquiries.sql"))],
            text=True, capture_output=True, env=env)
        if (result.returncode == 0) != success:
            raise AssertionError(result.stderr)

    try:
        sql("""
            CREATE TABLE users(userid bigint PRIMARY KEY);
            CREATE TABLE listings(listingid bigint PRIMARY KEY, owneruserid bigint REFERENCES users,
                                  tenantuserid bigint REFERENCES users);
            CREATE TABLE rentals(rentalid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                listingid bigint UNIQUE REFERENCES listings ON DELETE CASCADE,
                tenant_userid bigint, status text);
            CREATE TABLE chathistory(messageid bigint PRIMARY KEY, message text);
            CREATE TABLE listing_nearby_amenities(id bigint PRIMARY KEY,
                listing_id bigint REFERENCES listings ON DELETE CASCADE);
            CREATE TABLE listing_view(id bigint PRIMARY KEY,
                listingid bigint REFERENCES listings ON DELETE CASCADE);
            INSERT INTO users VALUES (1),(2),(3);
            INSERT INTO listings VALUES (10,1,NULL),(20,1,NULL),(30,1,NULL);
            INSERT INTO rentals(listingid,tenant_userid,status) VALUES (10,2,'terminated');
            INSERT INTO chathistory VALUES (1,'Existing plain text');
        """)
        migrate()
        migrate()
        assert sql("SELECT message FROM chathistory WHERE messageid=1") == "Existing plain text"
        sql("INSERT INTO rentals(listingid,tenant_userid,status) VALUES (10,3,'pending')")
        sql("INSERT INTO rentals(listingid,tenant_userid,status) VALUES (10,2,'active')", False)
        for state in ("NULL", "'ACTIVE'", "'unknown'"):
            sql(f"INSERT INTO rentals(listingid,tenant_userid,status) VALUES (20,2,{state})", False)
        sql("DELETE FROM listings WHERE listingid=10", False)
        assert sql("SELECT count(*) FROM rentals WHERE listingid=10") == "2"
        sql("""
            INSERT INTO chathistory VALUES (2,'Viewing?',20,'Original name','Original address');
            INSERT INTO listing_nearby_amenities VALUES (1,20);
            INSERT INTO listing_view VALUES (1,20);
            DELETE FROM listings WHERE listingid=20;
        """)
        assert sql("SELECT listingid IS NULL AND listing_name_snapshot='Original name' "
                   "AND listing_address_snapshot='Original address' FROM chathistory WHERE messageid=2") == "t"
        assert sql("SELECT count(*) FROM listing_nearby_amenities") == "0"
        assert sql("SELECT count(*) FROM listing_view") == "0"
        # Concurrent independent sessions compete for the same property.
        command = ["psql", "-X", "-v", "ON_ERROR_STOP=1", "-d", database, "-c",
                   "INSERT INTO rentals(listingid,tenant_userid,status) VALUES (30,2,'pending')"]
        first = subprocess.Popen(command, env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        second = subprocess.Popen(command, env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        first.communicate(); second.communicate()
        assert sorted([first.returncode == 0, second.returncode == 0]) == [False, True]
        # A failing preflight must not partially mutate the schema.
        sql("UPDATE listings SET tenantuserid=3 WHERE listingid=30")
        migrate(False)
        assert sql("SELECT count(*) FROM pg_indexes WHERE indexname='uq_listing_current_rental'") == "1"
        print("PASS: migration replay, history, uniqueness, statuses, deletion snapshots, concurrency, and preflight rollback.")
    finally:
        subprocess.run(["dropdb", database], env=env, check=True)


if __name__ == "__main__":
    main()
